import { AsyncLocalStorage } from 'node:async_hooks';
import { randomUUID } from 'node:crypto';
import { Injectable } from '@nestjs/common';

type Role = 'api' | 'worker';
interface TraceContext {
  correlationId: string;
  role: Role;
}

// One storage instance is shared by Express middleware, injectable services and Pino.
const storage = new AsyncLocalStorage<TraceContext>();
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

export function currentTraceContext(): Readonly<TraceContext> | undefined {
  return storage.getStore();
}

@Injectable()
export class CorrelationContext {
  getCorrelationId(): string | undefined {
    return currentTraceContext()?.correlationId;
  }

  /** The HTTP id is generated by correlationIdMiddleware, never taken from a client header. */
  run<T>(correlationId: string, role: Role, callback: () => T): T {
    return storage.run({ correlationId, role }, callback);
  }

  /** Start before validating a message so even malformed input has a trace for its rejection. */
  runForMessage<T>(message: unknown, callback: () => T): T {
    const candidate =
      message !== null && typeof message === 'object' && 'correlationId' in message
        ? message.correlationId
        : undefined;
    const id = typeof candidate === 'string' && UUID.test(candidate) ? candidate : randomUUID();
    return this.run(id, 'worker', callback);
  }
}
