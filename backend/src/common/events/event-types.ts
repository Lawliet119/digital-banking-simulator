/**
 * The asynchronous events of the system, as they travel through `outbox_events` and SQS
 * (docs/components/_shared/event-contract.md is the single source of their shape).
 *
 * Why this exists: producers and consumers each defined the event they thought they sent or
 * received, so a renamed field only showed up as a wrong number in production. One definition, used
 * on both sides, turns the difference into a compile error (these types) or a test failure
 * (`validateEvent` over samples typed with them).
 *
 * Everything on the wire is a string, a boolean or null: money is a canonical decimal string
 * (`@common/money`), times and ids are strings.
 */

export const EVENT_TYPES = {
  TransferCompleted: 'TransferCompleted',
  AccountStatusChanged: 'AccountStatusChanged',
} as const;

interface EventBase {
  /** uuid; consumers dedupe on it (`processed_events`). */
  eventId: string;
  /** ISO-8601 UTC with `Z`. For TransferCompleted: `transfers.created_at` (the database clock). */
  occurredAt: string;
  /** uuid, generated by the server. */
  correlationId: string;
}

/**
 * The fields every TransferCompleted has. A new field goes HERE and not on one branch below: the
 * schema is checked against `keyof TransferCompleted`, and `keyof` of a union only sees the keys
 * its branches share, so a key added to one branch only would slip past that check.
 */
export interface TransferCompletedCommon extends EventBase {
  eventType: 'TransferCompleted';
  transferId: string;
  fromAccountId: string;
  toAccountId: string;
  /** Whole dong, greater than zero (`parsePositiveMoney`). */
  amount: string;
  /**
   * Snapshot of the source balance before the transfer, signed (`parseBalance`). Negative when the
   * source is the SYSTEM `funding` account (ADR-09).
   */
  fromBalanceBefore: string;
  /** Snapshot, ISO-8601 UTC. */
  fromAccountCreatedAt: string;
  /** Snapshot, ISO-8601 UTC. */
  toAccountCreatedAt: string;
  /** Owner of the destination account at the time of the transfer. */
  toUserId: string;
}

/**
 * A completed transfer or deposit. `type` decides two fields, so writing a DEPOSIT with an owner
 * for the funding account is a compile error, not a bad message found later:
 *  - TRANSFER: `fromUserId` is the sender, `sameOwner` says whether both accounts have one owner.
 *  - DEPOSIT: the source is the SYSTEM funding account, which has no owner (BL-002).
 */
export type TransferCompleted = TransferCompletedCommon &
  (
    | { type: 'TRANSFER'; fromUserId: string; sameOwner: boolean }
    | { type: 'DEPOSIT'; fromUserId: null; sameOwner: false }
  );

/**
 * An operator locked or unlocked an account. It carries no reason: the reason lives in `audit_log`
 * and a customer notification never states a fraud reason (BR-13).
 */
export interface AccountStatusChanged extends EventBase {
  eventType: 'AccountStatusChanged';
  accountId: string;
  /** `users.id` of the account owner, so `notification` knows whom to tell. */
  ownerUserId: string;
  newStatus: 'ACTIVE' | 'LOCKED';
  /** The employee who did it; cross-reference with `audit_log`. */
  changedByUserId: string;
}

export type DomainEvent = TransferCompleted | AccountStatusChanged;

export type EventType = DomainEvent['eventType'];
